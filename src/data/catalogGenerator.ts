  // Construct Category Tree
  const categories: CategoryNode[] = [];

  const getOrCreateCategory = (parts: string[]): CategoryNode => {
    let currentLevel = categories;
    let currentPath = '';
    let targetNode: CategoryNode | null = null;

    for (let i = 0; i < parts.length; i++) {
      const part = parts[i];
      currentPath = currentPath ? `${currentPath}/${part}` : part;
      let existing = currentLevel.find((c) => c.name === part);

      if (!existing) {
        existing = {
          id: currentPath,
          name: part,
          path: currentPath,
          children: [],
          books: []
        };
        currentLevel.push(existing);
      }

      targetNode = existing;
      if (!existing.children) existing.children = [];
      currentLevel = existing.children;
    }

    return targetNode!;
  };

  // Populate books into categories
  for (const book of books) {
    const parts = book.categoryPath.split('/');
    const cat = getOrCreateCategory(parts);
    if (!cat.books) cat.books = [];
    cat.books.push(book);
  }

  return { books, categories };
